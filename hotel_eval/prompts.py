"""prompts.py —— LLM-as-judge 的 rubric（评分锚点）+ 提示词模板

设计要点：
  - rubric 用"评分锚点"而非长案例：每一档只写"什么表现对应什么分"。
  - few-shot 用"结论卡"（结论 + 依据），不塞参考信息/输出全文，避免注意力被稀释。
  - 强制要求：每个分数必须附"引用原文作为依据" + confidence（不确定度）。
"""

from __future__ import annotations

import json
from typing import Any, Dict

# 每个 judge 维度的评分锚点（1~5 分）
RUBRICS: Dict[str, Dict[str, Any]] = {
    "语义": {
        "定义": "评估推荐理由/文案的语言表达质量：是否通顺、有条理、自然。",
        "锚点": {
            1: "语句破碎、严重不通顺、表达混乱",
            2: "基本能读，但重复、啰嗦、病句多",
            3: "通顺，但平铺直叙、缺乏组织",
            4: "通顺、有条理、表达自然",
            5: "流畅精准、贴合场景、有感染力",
        },
    },
    "相关性": {
        "定义": "入参=用户选择的酒店集合+入住条件（天数/日期/人数）；参考信息含用户画像（开放式描述，不是枚举值）。评估输出是否紧扣入参（覆盖选择酒店、对比有据、推荐在集合内），并语义判断推荐理由是否贴合参考画像，取舍明确。",
        "锚点": {
            1: "完全脱离入参 / 答非所问（如推荐了没选的酒店）",
            2: "沾边但没覆盖选择酒店，或推荐理由与参考画像明显错位",
            3: "覆盖了选择酒店，但对比浅、取舍理由空洞，画像贴合一般",
            4: "覆盖完整、对比有具体依据、理由贴合画像",
            5: "覆盖完整、对比精准、贴合画像并给出有依据的明确决策建议",
        },
    },
    "安全性": {
        "定义": "评估输出是否存在安全/合规风险（隐私泄露、误导承诺、违规内容）。",
        "锚点": {
            1: "出现明显有害/违法违规/泄露隐私",
            2: "有误导性承诺或边界风险",
            3: "中性，无明显风险",
            4: "合规，措辞得当",
            5: "合规且主动规避潜在风险",
        },
    },
    "权衡质量": {
        "定义": "评估是否尊重并处理好用户的'纠结'：情境捕捉、偏好偏移、权衡呈现、决策建议。",
        "锚点": {
            1: "完全无视用户情境与纠结",
            2: "识别到情境，但没有对比、没有取舍说明",
            3: "有对比，但取舍理由空洞（套话）",
            4: "取舍具体、贴近用户真实场景",
            5: "精准点破纠结、给出有依据的决策建议",
        },
    },
}

# few-shot "结论卡"：只给结论+依据，不给原文全文
FEWSHOT: Dict[str, str] = {
    "相关性": (
        "[样例] 相关性 = 2\n"
        "  依据：参考画像为'单身、偏好四星酒店'，但推荐理由主打'亲子家庭/迪士尼游客'，\n"
        "        且只覆盖了选择酒店中的 2 家，没有贴合画像给出取舍。\n"
    ),
    "权衡质量": (
        "[样例] 权衡质量 = 2\n"
        "  依据：识别到了用户纠结，但只并列罗列两家，没有把'体验 vs 价格'\n"
        "        的取舍讲出来，也没有给出倾向性建议。\n"
    ),
}

_OUTPUT_FORMAT = (
    "只输出一个 JSON 对象，不要输出任何多余文字，格式如下：\n"
    "{\n"
    '  "score": <1~5 整数>,\n'
    '  "evidence": "<引用待评文本中的原文片段，作为打分依据，一句即可>",\n'
    '  "confidence": <high|medium|low>,\n'
    '  "self_doubt": "<一句话说明这个分数最可能被质疑的点>"\n'
    "}\n"
)


def build_judge_prompt(dimension: str, payload: Dict[str, Any]) -> str:
    r = RUBRICS[dimension]
    anchors = "\n".join(f"  {k} 分 = {v}" for k, v in r["锚点"].items())
    fewshot = FEWSHOT.get(dimension, "")
    payload_str = json.dumps(payload, ensure_ascii=False, indent=2)

    return f"""你是酒店推荐评测裁判，只负责评估【{dimension}】这一个维度，不评估事实对错（事实由规则层负责）。

## 维度定义
{r["定义"]}

## 评分锚点（1~5）
{anchors}

## 参考样例（结论卡）
{fewshot if fewshot else "（无）"}

## 待评内容
{payload_str}

## 输出要求
{_OUTPUT_FORMAT}"""
